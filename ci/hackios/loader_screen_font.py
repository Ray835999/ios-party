    assert not missing, missing
    bad = [c for c, g in GLYPHS.items() if len(g) != 7 or any(len(r) != 5 for r in g)]
    assert not bad, bad
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == 'c':
        sys.stdout.write(emit())
