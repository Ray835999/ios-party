def preview(code):
    rows = GLYPHS[chr(code)]
    print('+' + '-' * 5 + '+')
    for r in rows:
        print('|' + r.replace(' ', '.') + '|')
    print('+' + '-' * 5 + '+')


def emit():
    """The table as C: one line a glyph, seven bytes, bit 4 the leftmost column."""
    lines = ["static const uint8_t font5x7[95][7] = {"]
    for code in range(0x20, 0x7f):
        rows = GLYPHS[chr(code)]
        values = []
        for row in rows:
            v = 0
            for i, ch in enumerate(row):
                if ch == '#':
                    v |= 0x10 >> i
            values.append(v)
        shown = chr(code) if 0x20 < code < 0x7f and chr(code) not in "'\\" else '?'
        lines.append("\t{ %s },%s/* %02x %s */" % (
            ", ".join("0x%02x" % v for v in values),
            " " * 2,
            code,
            shown,
        ))
    lines.append("};")
    return "\n".join(lines) + "\n"


